	public string CurrentCode => _code;

	public void SetCurrent(string code)
	{
		string c = string.IsNullOrEmpty(code) ? "zh-CN" : code;
		if (!_maps.ContainsKey(c)) c = "zh-CN";
		if (_code == c) return;
		_code = c;
		PropertyChanged?.Invoke(this, new PropertyChangedEventArgs("Item[]"));
	}

	public string this[string key]
	{
		get
		{
			if (_maps.TryGetValue(_code, out var m) && m.TryGetValue(key, out string? v)) return v;
			if (_maps.TryGetValue("zh-CN", out var zh) && zh.TryGetValue(key, out string? fallback)) return fallback;
			return key;
		}
	}

	public string Format(string key, params object?[] args)
	{
		try
		{
			return string.Format(this[key], args);
		}
		catch
		{
			return this[key];
		}
	}

