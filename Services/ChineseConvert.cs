	private static Dictionary<char, char> Build(string keys, string values)
	{
		var map = new Dictionary<char, char>(keys.Length);
		for (int i = 0; i < keys.Length; i++)
		{
			map[keys[i]] = values[i];
		}
		return map;
	}

	/// <summary>逐字转简。</summary>
	public static string ToSimplified(string text)
	{
		return Map(text, TradToSimp);
	}

	/// <summary>逐字转繁。</summary>
	public static string ToTraditional(string text)
	{
		return Map(text, SimpToTrad);
	}

	/// <summary>单个字转简，没得转就原样返回。
	/// 和 <see cref="ToSimplified(string)"/> 是同一张表，只是逐字查——
	/// 搜索匹配要用它做「归一化同时记住原文下标」，
	/// 表本身是一对一的，所以长度不变、下标不会错位。</summary>
	public static char ToSimplifiedChar(char c)
	{
		return TradToSimp.TryGetValue(c, out char to) ? to : c;
	}

	/// <summary>单个字转繁。</summary>
	public static char ToTraditionalChar(char c)
	{
		return SimpToTrad.TryGetValue(c, out char to) ? to : c;
	}

	/// <summary>单个字把日文新字体折回简体（「砕」->「碎」）。没得折就原样返回。
	/// 语义上和 <see cref="ToSimplifiedChar"/> 一样是「一对一的等价字」，
	/// 所以逐字替换、长度不变，高亮反查下标不会错位。</summary>
	public static char FoldVariantChar(char c)
	{
		return VariantFold.TryGetValue(c, out char to) ? to : c;
	}

	/// <summary>归一化一个字：先转简体，再把新字体折回简体。
	///
	/// 顺序不能反。折叠表的目标全是已经是简体的字，所以先折叠再转简体也行；
	/// 但先转简体能少走一步——像「偽」这种字简繁表一步就到位（压根不认它是日文新字体），
	/// 转完已经是「伪」，折叠表就不会被问到。
	///
	/// 搜索匹配只用这一个入口，别处再单独调 <see cref="ToSimplifiedChar"/> 就漏掉新字体了。</summary>
	public static char NormalizeChar(char c)
	{
		return FoldVariantChar(ToSimplifiedChar(c));
	}

	/// <summary>归一化整个字符串，见 <see cref="NormalizeChar"/>。</summary>
	public static string Normalize(string text)
	{
		if (string.IsNullOrEmpty(text))
		{
			return text ?? "";
		}
		return Map(text, TradToSimp, VariantFold);
	}

	/// <summary>按一组映射逐字改写。<paramref name="maps"/> 按顺序依次套用，
	/// 所以调用方能表达「先转简体、再折新字体」这种流水线。</summary>
	private static string Map(string text, params Dictionary<char, char>[] maps)
	{
		if (string.IsNullOrEmpty(text) || maps.Length == 0)
		{
			return text ?? "";
		}
		// start 记住「还没写进 sb 的那一段的起点」。
		// 不能用 sb.Append(text, 0, i) 这种写法：sb 是碰到第一个要转的字才 new 的，
		// 第二个要转的字会把已经拼好的前缀再追加一遍，整串都被重复；
		// 而开头那段没被转过的字又会因为 sb 当时还不存在被丢掉。
		StringBuilder? sb = null;
		int start = 0;
		for (int i = 0; i < text.Length; i++)
		{
			char cur = text[i];
			char to = cur;
			foreach (Dictionary<char, char> map in maps)
			{
				if (map.Count != 0 && map.TryGetValue(to, out char next))
				{
					to = next;
				}
			}
			if (to == cur)
			{
				continue;
			}
			sb ??= new StringBuilder(text.Length);
			sb.Append(text, start, i - start);
			sb.Append(to);
			start = i + 1;
		}
		if (sb == null)
		{
			return text;
		}
		sb.Append(text, start, text.Length - start);
		return sb.ToString();
	}
